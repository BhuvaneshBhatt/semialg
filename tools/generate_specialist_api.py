"""Generate an index of specialist namespaces from public exports and live signatures."""

from __future__ import annotations

import argparse
import importlib
import inspect
import pkgutil
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = tomllib.loads((ROOT / "pyproject.toml").read_text())["project"]["name"]
DESTINATION = ROOT / (
    "docs/reference/expert_api.md" if PACKAGE == "semialg" else "docs/specialist-api.md"
)


def render():
    """Index owned exports without duplicating wrappers around backend implementations."""
    package = importlib.import_module(PACKAGE)
    lines = [
        "# Specialist API index",
        "",
        "Generated by `python tools/generate_specialist_api.py`. Run with `--check` to detect stale exports or signatures. Mathematical support and failure guarantees are defined in the owning guides, not by an export name alone.",
        "",
    ]
    if PACKAGE == "semialg":
        from semialg._api_policy import EXPERT_EXPORTS

        groups = {}
        for name, module in EXPERT_EXPORTS.items():
            groups.setdefault(PACKAGE + module, []).append(name)
    else:
        groups = {}
        for info in sorted(
            pkgutil.walk_packages(package.__path__, PACKAGE + "."), key=lambda i: i.name
        ):
            if any(part.startswith("_") for part in info.name.split(".")):
                continue
            module = importlib.import_module(info.name)
            names = getattr(module, "__all__", ())
            if names:
                groups[info.name] = sorted(names)
    for module_name, names in sorted(groups.items()):
        module = importlib.import_module(module_name)
        lines.extend([f"## `{module_name}`", "", "| Name | Signature or kind |", "| --- | --- |"])
        for name in sorted(names):
            value = getattr(module, name)
            try:
                signature = (
                    str(inspect.signature(value)) if callable(value) else type(value).__name__
                )
            except (TypeError, ValueError):
                signature = "type" if inspect.isclass(value) else "callable"
            # Parent object representations can include process-specific addresses.
            signature = __import__("re").sub(r" at 0x[0-9A-Fa-f]+", "", signature)
            signature = signature.replace("|", "\\|").replace("\n", " ")
            lines.append(f"| `{name}` | `{signature}` |")
        lines.append("")
    return "\n".join(lines)


def main():
    """Write the index or fail when a checked-in index is out of date."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = render()
    if args.check:
        if not DESTINATION.is_file() or DESTINATION.read_text() != content:
            parser.exit(1, "Specialist API index is stale\n")
    else:
        DESTINATION.write_text(content)
    print("Specialist API index is current")


if __name__ == "__main__":
    main()
